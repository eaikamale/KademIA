/**
 * Função utilitária com busca normalizada (case-insensitive e tolerante a variações)
 * para garantir que todo exercício retorne a mídia local correta.
 */
export function getExerciseGif(name) {
  if (!name) return null;
  
  // 1. Chave exata
  if (exerciseGifs[name]) return exerciseGifs[name];
  
  // 2. Busca normalizada por substring
  const n = name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  
  if (n.includes("supino reto")) return exerciseGifs["Supino Reto (Barra ou Halteres)"];
  if (n.includes("supino inclinado")) return exerciseGifs["Supino Inclinado com Halteres"];
  if (n.includes("crucifixo maquina") || n.includes("pec deck") || n.includes("crucifixo")) return exerciseGifs["Crucifixo Máquina (Pec Deck)"];
  if (n.includes("desenvolvimento")) return exerciseGifs["Desenvolvimento com Halteres"];
  if (n.includes("elevacao lateral polia")) return exerciseGifs["Elevação Lateral na Polia Baixa"];
  if (n.includes("elevacao lateral")) return exerciseGifs["Elevação Lateral com Halteres"];
  if (n.includes("elevacao frontal")) return exerciseGifs["Elevação Frontal na Polia"];
  if (n.includes("crucifixo inverso")) return exerciseGifs["Crucifixo Inverso (Máquina ou Halteres)"];
  if (n.includes("facepull") || n.includes("face pull")) return exerciseGifs["Facepull na Polia Alta"];
  if (n.includes("triceps pulley") || n.includes("triceps corda") || n.includes("triceps barra")) return exerciseGifs["Tríceps Pulley Barra"];
  if (n.includes("triceps testa")) return exerciseGifs["Tríceps Testa + Mergulho Banco"];
  if (n.includes("mergulho banco")) return exerciseGifs["Tríceps Testa + Mergulho Banco"];
  if (n.includes("panturrilha")) return exerciseGifs["Panturrilha em Pé"];
  if (n.includes("extensora")) return exerciseGifs["Cadeira Extensora"];
  if (n.includes("agachamento sumo")) return exerciseGifs["Agachamento Sumô"];
  if (n.includes("agachamento")) return exerciseGifs["Agachamento (Livre ou Smith)"];
  if (n.includes("stiff")) return exerciseGifs["Stiff com Halteres ou Barra"];
  if (n.includes("legpress") || n.includes("leg press") || n.includes("leg 45") || n.includes("leg 180")) return exerciseGifs["Leg Press 180°"];
  if (n.includes("afundo")) return exerciseGifs["Afundo com Halteres"];
  if (n.includes("mesa flexora") || n.includes("flexora deitada") || n.includes("flexora deitado")) return exerciseGifs["Mesa Flexora"];
  if (n.includes("flexora")) return exerciseGifs["Flexora em Pé"];
  if (n.includes("adutora") || n.includes("aducao")) return exerciseGifs["Cadeira Adutora / Abdutora"];
  if (n.includes("abdutora") || n.includes("abducao")) return exerciseGifs["Cadeira Adutora / Abdutora"];
  if (n.includes("puxada alta")) return exerciseGifs["Puxada Alta Pronada"];
  if (n.includes("remada baixa") || n.includes("remada pronada") || n.includes("remada neutra")) return exerciseGifs["Remada Baixa Pronada"];
  if (n.includes("remada alta")) return exerciseGifs["Remada Alta Polia Baixa + Encolhimento"];
  if (n.includes("encolhimento")) return exerciseGifs["Encolhimento com Halteres"];
  if (n.includes("rosca direta")) return exerciseGifs["Rosca Direta com Barra"];
  if (n.includes("rosca martelo")) return exerciseGifs["Rosca Martelo com Halteres"];
  if (n.includes("hip thrust") || n.includes("elevacao de quadril")) return exerciseGifs["Elevação de Quadril Máquina (Hip Thrust)"];
  if (n.includes("prancha")) return exerciseGifs["Abdominal Prancha Baixa"];
  if (n.includes("abdominal infra") || n.includes("elevacao pernas")) return exerciseGifs["Abdominal Infra / Elevação Pernas"];
  if (n.includes("abdominal")) return exerciseGifs["Abdominal Supra na Polia com Carga"];
  if (n.includes("cardio") || n.includes("esteira") || n.includes("corrida") || n.includes("trote")) return exerciseGifs["Cardio Moderado (Esteira)"];
  if (n.includes("mobilidade")) return exerciseGifs["Mobilidade de Ombro c/ Bastão"];

  return null;
}
